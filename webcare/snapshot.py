"""Catalog snapshots: run the catalog checks without a database connection.

Some machines cannot open a Postgres connection at all (only web traffic
leaves them). For those, an administrator runs one read-only statement through
whatever route they already have (the SQL editor, for example), saves its
single JSON result to a file, and the checks run on that file.

The statement is built here from the same SQL the live checks execute, so both
paths judge alike. The snapshot carries names and yes/no facts only: no
function bodies, no policy expressions, no rows from any application table.

A snapshot says what the catalog looked like when it was taken, by whoever
took it. The tool cannot verify where a file came from, so every snapshot
carries a label chosen by the person who took it, and a snapshot is only
judged against a target of the same name.
"""

from __future__ import annotations

import json
import re
from pathlib import Path
from typing import Iterable, Optional, Sequence, Union

from . import live
from .model import CheckResult, Refusal
from .targets import Target

FORMAT = "webcare-catalog-snapshot/1"
SNAPSHOT_SQL_FILE = Path(__file__).resolve().parent.parent / "sql" / "catalog-snapshot.sql"
DEFAULT_LABEL = "unlabelled"
MAX_BYTES = 20 * 1024 * 1024

_IDENTIFIER = re.compile(r"^[a-z_][a-z0-9_]{0,62}$")
_LABEL = re.compile(r"^[A-Za-z0-9][A-Za-z0-9._-]{0,63}$")


def _text_array(values: Iterable[str]) -> str:
    return "array[" + ", ".join(f"'{value}'" for value in values) + "]::text[]"


def _indent(sql: str, spaces: int) -> str:
    pad = " " * spaces
    return "\n".join(pad + line if line else line for line in sql.strip().splitlines())


def build_sql(schemas: Sequence[str] = ("public",), label: str = DEFAULT_LABEL) -> str:
    """One read-only SELECT that returns the whole snapshot as a single JSON value."""
    schemas = list(schemas)
    if not schemas:
        raise Refusal("a snapshot needs at least one schema")
    for schema in schemas:
        if not _IDENTIFIER.match(schema):
            raise Refusal(
                f"schema name {schema!r} is not a plain lower-case identifier; "
                "the snapshot statement only accepts names it can write without quoting"
            )
    if not _LABEL.match(label):
        raise Refusal("a snapshot label may hold letters, digits, dot, dash and underscore only")

    schema_array = _text_array(schemas)
    kinds_array = _text_array(live.RELATION_KINDS)

    def bind(sql: str) -> str:
        return sql.replace("%(schemas)s", schema_array).replace("%(kinds)s", kinds_array)

    extra_parts = []
    for check in live.load_extra_checks():
        extra_parts.append(
            f"    '{check.id}', coalesce((\n"
            f"      select jsonb_agg(to_jsonb(q)) from (\n{_indent(bind(check.sql), 8)}\n"
            f"        limit {live.MAX_ROWS_PER_EXTRA_CHECK}\n      ) q\n    ), '[]'::jsonb)"
        )
    extra = ",\n".join(extra_parts)

    return f"""-- supabase-web-care catalog snapshot, format {FORMAT}
--
-- One read-only SELECT over the system catalog. It returns a single row with a
-- single JSON value: names of schemas, tables, policies and functions, and
-- yes/no facts about them. It reads no row of any application table and
-- returns no function body and no policy expression.
--
-- Generated by `python -m webcare snapshot-sql`; do not edit the queries.
-- Save the JSON result to a file and run:
--     python -m webcare check --snapshot <file> --target <name>
-- The label below must equal the name of that target in webcare.toml.
select jsonb_build_object(
  'format', '{FORMAT}',
  'label', '{label}',
  'taken_at', to_char(now() at time zone 'utc', 'YYYY-MM-DD"T"HH24:MI:SS"Z"'),
  'server_version', current_setting('server_version'),
  'database', current_database(),
  'schemas', to_jsonb({schema_array}),
  'anon_role_exists', exists (select 1 from pg_catalog.pg_roles where rolname = 'anon'),
  'definer_functions', coalesce((
    select jsonb_agg(to_jsonb(q)) from (
{_indent(bind(live._DEFINER_FUNCTIONS_SQL), 6)}
    ) q
  ), '[]'::jsonb),
  'anon_readable', coalesce((
    select jsonb_object_agg(q.schema_name, q.relations) from (
      select n.nspname::text as schema_name,
             jsonb_agg(c.relname::text order by c.relname) as relations
        from pg_catalog.pg_class c
        join pg_catalog.pg_namespace n on n.oid = c.relnamespace
       where n.nspname = any({schema_array})
         and c.relkind::text = any({kinds_array})
         and case when exists (select 1 from pg_catalog.pg_roles where rolname = 'anon')
                  then pg_catalog.has_table_privilege('anon', c.oid, 'SELECT')
                  else false end
       group by n.nspname
    ) q
  ), '{{}}'::jsonb),
  'extra', jsonb_build_object(
{extra}
  )
) as snapshot;
"""


def load(path: Path) -> dict:
    """Read a snapshot file, accepting the wrappers common tools put around it."""
    try:
        if path.stat().st_size > MAX_BYTES:
            raise Refusal(f"snapshot file {path.name} is larger than {MAX_BYTES // (1024 * 1024)} MB")
        data = json.loads(path.read_text(encoding="utf-8-sig"))
    except OSError as error:
        raise Refusal(f"could not read snapshot file {path} ({type(error).__name__})") from None
    except ValueError:
        raise Refusal(f"snapshot file {path.name} is not valid JSON") from None
    return parse(data, path.name)


def statement_body(sql: str) -> str:
    """The statement without its explanatory comment lines."""
    return "\n".join(line for line in sql.splitlines() if not line.strip().startswith("--"))


def parse(data, name: str) -> dict:
    """Validate a snapshot value, however the tool that returned it wrapped it."""
    # SQL editors and APIs return rows: [{"snapshot": {...}}] or {"snapshot": "..."}.
    for _ in range(4):
        if isinstance(data, list) and len(data) == 1:
            data = data[0]
        elif isinstance(data, dict) and "snapshot" in data and "format" not in data:
            data = data["snapshot"]
        elif isinstance(data, str):
            try:
                data = json.loads(data)
            except ValueError:
                break
        else:
            break
    if not isinstance(data, dict) or data.get("format") != FORMAT:
        raise Refusal(
            f"{name} is not a catalog snapshot in format {FORMAT}. Generate the statement "
            "with `python -m webcare snapshot-sql` and save its JSON result unchanged."
        )
    for key, kind in (
        ("label", str), ("taken_at", str), ("schemas", list), ("definer_functions", list),
        ("anon_readable", dict), ("extra", dict), ("anon_role_exists", bool),
    ):
        if not isinstance(data.get(key), kind):
            raise Refusal(f"snapshot {name} is missing `{key}` or it has the wrong type")
    for row in data["definer_functions"]:
        if not isinstance(row, dict) or not {
            "schema_name", "function_name", "arg_types", "public_may", "anon_may"
        } <= row.keys():
            raise Refusal(f"snapshot {name} has a malformed entry in `definer_functions`")
    return data


def describe(snapshot: dict, source: Union[Path, str]) -> str:
    """What was examined. `source` is a file, or text saying where the tool fetched it."""
    facts = (
        f"taken {snapshot['taken_at']} from database {snapshot.get('database', '?')!r} "
        f"(Postgres {snapshot.get('server_version', '?')}), schemas "
        f"{', '.join(snapshot['schemas'])}"
    )
    if isinstance(source, Path):
        return (
            f"catalog snapshot file {source.name}, labelled {snapshot['label']!r}, {facts}; "
            "the file's origin is as its label states and was not verified"
        )
    return f"catalog snapshot {source}, {facts}"


def ensure_matches(snapshot: dict, target: Target) -> None:
    """A snapshot is only judged against the target it was labelled for."""
    label = snapshot["label"]
    if label == DEFAULT_LABEL:
        raise Refusal(
            "the snapshot still carries the default label. Regenerate the statement with "
            f"`python -m webcare snapshot-sql --label {target.name}` so the file says which "
            "database it came from."
        )
    if label != target.name:
        raise Refusal(
            f"the snapshot is labelled {label!r} but the target is {target.name!r}. "
            "Refusing to judge one database by another's allowlist."
        )
    missing = [schema for schema in target.schemas if schema not in snapshot["schemas"]]
    if missing:
        raise Refusal(
            f"target {target.name!r} covers schema(s) {', '.join(missing)} that the snapshot "
            "does not include; take the snapshot again with those schemas"
        )


def run_checks(
    snapshot: dict, source: Union[Path, str], target: Optional[Target]
) -> list[CheckResult]:
    """The catalog checks, judged from a snapshot instead of a connection."""
    evidence = describe(snapshot, source)
    schemas = list(target.schemas) if target else list(snapshot["schemas"])
    expected = target.expected_anon_functions if target else ()

    extra = CheckResult(id="extra_live", title=live.EXTRA_TITLE, evidence=evidence)
    for check in live.load_extra_checks():
        rows = snapshot["extra"].get(check.id)
        if not isinstance(rows, list):
            extra.notes.append(
                f"{check.id}: not in this snapshot (taken with an older statement); not judged"
            )
            continue
        live.add_extra_findings(extra, check, [r for r in rows if isinstance(r, dict)])
        if len(rows) >= live.MAX_ROWS_PER_EXTRA_CHECK:
            extra.notes.append(f"{check.id}: the snapshot holds only the first {len(rows)} rows")
    live.finish_extra_checks(extra)

    functions = CheckResult(id="functions_live", title=live.FUNCTIONS_TITLE, evidence=evidence)
    rows = [row for row in snapshot["definer_functions"] if row["schema_name"] in schemas]
    live.judge_function_exposure(functions, rows, snapshot["anon_role_exists"], schemas, expected)
    return [extra, functions]


def anon_readable(snapshot: dict, schema: str) -> list[str]:
    relations = snapshot["anon_readable"].get(schema, [])
    return [str(name) for name in relations] if isinstance(relations, list) else []
